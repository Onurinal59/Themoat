export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>(() => {
    const saved = localStorage.getItem("economicMoatLocale");
    if (saved === "tr" || saved === "en") return saved;
    if (typeof navigator !== "undefined" && navigator.language.startsWith("tr")) return "tr";
    return "en";
  });

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    localStorage.setItem("economicMoatLocale", lang);
  };

  const toggleLanguage = () => {
    setLanguage(language === "tr" ? "en" : "tr");
  };


  useEffect(() => {
    document.documentElement.lang = language;
    document.title = language === 'tr' ? 'Ekonomik Hendek Akademisi | Değer Yatırımı & ROIC' : 'Economic Moat Academy | Master Value Investing & ROIC';
    
    // Update meta tags
    const updateMeta = (selector, content) => {
      const el = document.querySelector(selector);
      if (el) el.setAttribute('content', content);
    };
    
    if (language === 'tr') {
      updateMeta('meta[name="description"]', "Michael Mauboussin'in ekonomik hendek çerçevesini, ROIC analizini ve tersine DCF değerlemelerini interaktif simülatörlerle öğrenin.");
      updateMeta('meta[property="og:title"]', "Ekonomik Hendek Akademisi | Değer Yatırımı & ROIC");
      updateMeta('meta[property="og:description"]', "Michael Mauboussin'in ekonomik hendek çerçevesini, ROIC analizini ve tersine DCF değerlemelerini interaktif simülatörlerle öğrenin.");
      updateMeta('meta[name="twitter:title"]', "Ekonomik Hendek Akademisi | Değer Yatırımı & ROIC");
      updateMeta('meta[name="twitter:description"]', "Michael Mauboussin'in ekonomik hendek çerçevesini, ROIC analizini ve tersine DCF değerlemelerini interaktif simülatörlerle öğrenin.");
    } else {
      updateMeta('meta[name="description"]', "Master Michael Mauboussin's economic moat framework, ROIC analysis, and reverse DCF valuations with interactive simulators.");
      updateMeta('meta[property="og:title"]', "Economic Moat Academy | Master Value Investing & ROIC");
      updateMeta('meta[property="og:description"]', "Master Michael Mauboussin's economic moat framework, ROIC analysis, and reverse DCF valuations with interactive simulators.");
      updateMeta('meta[name="twitter:title"]', "Economic Moat Academy | Master Value Investing & ROIC");
      updateMeta('meta[name="twitter:description"]', "Master Michael Mauboussin's economic moat framework, ROIC analysis, and reverse DCF valuations with interactive simulators.");
    }
  }, [language]);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const t = (key: string, defaultText?: string): string => {
    const langDict = UI_TRANSLATIONS[language];
    if (langDict && langDict[key]) {
      return langDict[key];
    }
    return defaultText || key;
  };

  const getModules = (): LearningModule[] => {
    return language === "en" ? MODULES_DATA_EN : MODULES_DATA;
  };

  const getGlossaryTerms = (): GlossaryTerm[] => {
    return language === "en" ? GLOSSARY_TERMS_EN : GLOSSARY_TERMS;
  };

  const getFormulaGuides = (): Record<string, FormulaGuide> => {
    if (language === "en") {
      return { ...FORMULA_GUIDES_DATA, ...FORMULA_GUIDES_DATA_EN };
    }
    return FORMULA_GUIDES_DATA;
  };

  const getChecklistItems = (): ChecklistItem[] => {
    return language === "en" ? CHECKLIST_ITEMS_EN : CHECKLIST_ITEMS;
  };

  const getFlashcards = (): Flashcard[] => {
    const raw = language === "en" ? INITIAL_FLASHCARDS_EN : INITIAL_FLASHCARDS;
    return raw.map((c) => ({
      ...c,
      hasBeenReviewed: c.hasBeenReviewed ?? false,
    }));
  };

  const getStepMethodologyGuides = (): Record<number, StepMethodologyGuide> => {
    return language === "en" ? STEP_METHODOLOGY_GUIDES_EN : STEP_METHODOLOGY_GUIDES;
  };

  const getInitialDossiers = (): CompanyAuditDossier[] => {
    return getInitialPresetDossiers(language === "en");
  };

  const getBalanceSheetGuide = (): any[] => {
    return language === "en" ? BALANCE_SHEET_GUIDE_EN : BALANCE_SHEET_GUIDE;
  };


  const formatPercent = (value: number, fractionDigits: number = 1): string => {
    return new Intl.NumberFormat(language === "tr" ? "tr-TR" : "en-US", {
      style: "percent",
      minimumFractionDigits: fractionDigits,
      maximumFractionDigits: fractionDigits,
    }).format(value / 100);
  };

  const formatCurrency = (value: number): string => {
    if (value === 0) return new Intl.NumberFormat(language === "tr" ? "tr-TR" : "en-US", { style: "currency", currency: "USD", minimumFractionDigits: 0, maximumFractionDigits: 0 }).format(0);
    return new Intl.NumberFormat(language === "tr" ? "tr-TR" : "en-US", {
      style: "currency",
      currency: "USD",
      notation: "compact",
      compactDisplay: "short",
      maximumFractionDigits: 1
    }).format(value);
  };

  const formatNumber = (value: number, fractionDigits: number = 0): string => {
    return new Intl.NumberFormat(language === "tr" ? "tr-TR" : "en-US", {
      minimumFractionDigits: fractionDigits,
      maximumFractionDigits: fractionDigits,
    }).format(value);
  };

  const formatDuration = (minutes: number): string => {
    return language === "tr" ? `${minutes} dk` : `${minutes} min`;
  };

  const getMasterTemplate = (): CompanyAuditDossier => {
    return language === "en" ? MAUBOUSSIN_GUIDED_TEMPLATE_EN : MAUBOUSSIN_GUIDED_TEMPLATE;
  };


  const formatPercentagePoints = (value: number, maxFD?: number) => fpp(value, language, maxFD);
  const formatUsdFromMillions = (value: number, maxFD?: number) => fumm(value, language, maxFD);
  const formatUsdFromBillions = (value: number, maxFD?: number) => fubb(value, language, maxFD);
  const formatMultiplier = (value: number, maxFD?: number) => fmul(value, language, maxFD);
  const formatDurationYears = (value: number) => fdy(value, language);

  return (
    <LanguageContext.Provider value={{
        language,
        setLanguage,
        toggleLanguage,
        isEnglish: language === "en",
        t,
        getModules,
        getGlossaryTerms,
        getFormulaGuides,
        getChecklistItems,
        getFlashcards,
        getStepMethodologyGuides,
        getInitialDossiers,
        getBalanceSheetGuide,
        getMasterTemplate,
    formatPercent,
    formatCurrency,
    formatNumber,
    formatDuration,

    formatPercentagePoints,
    formatUsdFromMillions,
    formatUsdFromBillions,
    formatMultiplier,
    formatDurationYears}}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = (): LanguageContextType => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used within a LanguageProvider");
  }
  return context;
};
